-- ================= GERAK =================
-- Force: gerak paksa per frame (langkah = speed * dt, tidak melewati target walau speed 19000)
local function forceMove(target, stop, speed, cond)
	S.floatOn, S.noclip = true, true
	stream(target)
	local t0 = os.clock()
	local reached = false
	while cond() and os.clock() - t0 < CFG.WALK_TIMEOUT do
		local h = hrp()
		if not h then break end
		local d = target - h.Position
		local dist = d.Magnitude
		if dist <= stop then reached = true break end
		local dt = RunService.Heartbeat:Wait()
		h = hrp()
		if not h then break end
		local step = math.min(dist, speed * dt)
		h.CFrame = CFrame.new(h.Position + d.Unit * step) * (h.CFrame - h.CFrame.Position)
		h.AssemblyLinearVelocity = Vector3.zero
	end
	S.noclip = false
	return reached
end

