	local h = hrp()
	if not h then return end
	setStatus("Starter -> Safe Zone (Force " .. CFG.START_SPEED .. ")")
	if h.Position.Y > 30 or (h.Position - CFG.STARTER).Magnitude < 80 then
		forceMove(CFG.STARTER, 3, CFG.START_SPEED, cond)
	end
	forceMove(CFG.SAFE, 4, CFG.START_SPEED, cond)
	S.floatOn, S.noclip = false, false
end

