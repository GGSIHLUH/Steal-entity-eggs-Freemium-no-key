			S.busy = true
			local cond = function() return S.alive and settings.farm and not S.boss end
			if not startedOnce then
				startedOnce = true
				local h = hrp()
				if h and h.Position.Y > 30 then goStartToSafe(cond) end
			end
			local z = settings.zone
			if z >= 1 and z <= #CFG.ZONES then
				farmZone(z, cond)
			else
				local from, to, step = 1, #CFG.ZONES, 1
				if settings.prio == "Terbagus" then from, to, step = #CFG.ZONES, 1, -1 end
				for i = from, to, step do
					if not cond() then break end
					if farmZone(i, cond) then break end
				end
			end
			S.busy = false
			task.wait(1.2)
		else
			task.wait(0.4)
		end
	end
end)

