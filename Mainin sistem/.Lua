local MULT = { k = 1e3, m = 1e6, b = 1e9, t = 1e12 }
local function parseNum(s)
	s = tostring(s or ""):lower():gsub(",", "")
	local num, suf = s:match("([%d%.]+)%s*([a-z]*)")
	num = tonumber(num)
	if not num then return nil end
	return num * (MULT[suf:sub(1, 1)] or 1)
end

local eggCache = {}
local function parseEgg(p)
	local c = eggCache[p]
	if c and os.clock() - c.t < 2 then return c end
	local model = ownerModel(p) or p.Parent
	local info = { t = os.clock(), name = "Telur", kg = 0, rank = 0, income = nil, animal = nil, score = 0 }
	if model then
		local texts = collectTexts(model)
		for k, v in pairs(model:GetAttributes()) do texts[#texts + 1] = tostring(k) .. ": " .. tostring(v) end
		for _, t in ipairs(texts) do
			local low = t:lower()
			if low:find("telur", 1, true) or low:find("egg", 1, true) then info.name = t end
			if info.rank == 0 then
				for _, r in ipairs(CFG.RARITY) do
					if low:find(r[1], 1, true) then info.rank = r[2] break end
				end
			end
			local kg = low:match("([%d%.,]+)%s*kg")
			if kg then info.kg = tonumber((kg:gsub(",", ""))) or info.kg end
			local inc = low:match("([%d%.,]+%s*%a?)%s*/%s*s")
			if inc and not info.income then info.income = parseNum(inc) end
			local an = low:match("hewan%s*:%s*(.+)") or low:match("pet%s*:%s*(.+)") or low:match("animal%s*:%s*(.+)")
			if an then info.animal = an end
		end
		for _, k in ipairs({ "PetName", "Pet", "Animal", "Hewan", "AnimalName" }) do
			local v = model:GetAttribute(k)
			if v then info.animal = tostring(v) end
		end
	end
	info.score = info.rank * 1e6 + info.kg
	eggCache[p] = info
	return info
end

