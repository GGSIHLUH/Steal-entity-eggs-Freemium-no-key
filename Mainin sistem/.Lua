local function placeEgg()
	local h = hrp()
	if not h then return end
	local best, bd = nil, CFG.SAFE_RADIUS
	for p in pairs(prompts) do
		if p.Parent and p.Enabled and isPlace(p) then
			local pos = promptPos(p)
			if pos and (pos - CFG.SAFE).Magnitude <= bd then best, bd = p, (pos - CFG.SAFE).Magnitude end
		end
	end
	if best then
		local pos = promptPos(best)
		if (pos - h.Position).Magnitude > 8 then
			setPos(h, pos + Vector3.new(0, 3, 0))
			task.wait(0.1)
		end
		fire(best)
		return true
	end
	return false -- kemungkinan egg otomatis tersimpan di safe zone
end

-- ================= PILIH EGG =================
local function eggPrompts(center, matcher)
	local list = {}
	local mychar = LocalPlayer.Character
	for p in pairs(prompts) do
		if p.Parent and p.Enabled and not (mychar and p:IsDescendantOf(mychar)) and matcher(p) then
			local pos = promptPos(p)
			if pos and (pos - center).Magnitude <= CFG.ZONE_RADIUS and (pos - CFG.SAFE).Magnitude > CFG.SAFE_RADIUS then
				list[#list + 1] = { p = p, pos = pos }
			end
		end
	end
	return list
end

local function pickEgg(center)
	local list = eggPrompts(center, isTake)
	if #list == 0 then list = eggPrompts(center, isOther) end
	if #list == 0 then return nil, nil end
	local h = hrp()
	local best, bs
	for _, e in ipairs(list) do
		local score
		if settings.prio == "Terbagus" then
			score = parseEgg(e.p).score
		else
			score = h and -(e.pos - h.Position).Magnitude or 0
		end
		if not bs or score > bs then best, bs = e, score end
	end
	return best.p, best.pos
end

local function waitRender(center, cond)
	stream(center)
	local t0 = os.clock()
	repeat
		if #eggPrompts(center, isTake) > 0 or #eggPrompts(center, isOther) > 0 then
			task.wait(0.5) -- beri waktu prompt lain ikut ter-render
			return true
		end
		task.wait(0.25)
	until os.clock() - t0 >= CFG.RENDER_WAIT or not cond()
	return false
end

-- ================= FARMING 1 ZONE =================
local function farmZone(zi, cond)
	local z = CFG.ZONES[zi]
	if not z then return false end
	local camera = Workspace.CurrentCamera
	local clone
	local result = false

	local function restoreCam()
		local hm = hum()
		if camera and hm then camera.CameraSubject = hm end
	end
	local function finish()
		S.floatOn, S.noclip = false, false
		restoreCam()
		if clone then clone:Destroy() clone = nil end
	end

	local ok, err = pcall(function()
		local h = hrp()
		if not h then return end
		local method = settings.method

		-- 1) klon dulu, kamera ke klon
		local chm
		clone, chm = createClone()
		if chm and camera then camera.CameraSubject = chm end

		-- 2) karakter asli TP ke zone
		setStatus(string.format("[M%d] TP ke %s", method, z.name))
		stream(z.pos)
		setPos(h, z.pos + Vector3.new(0, 1, 0))
		task.wait(0.15)

		-- 3) tunggu map render
		local rendered = waitRender(z.pos, cond)

		-- Mentode 1: kamera balik ke karakter asli setelah render
		if method == 1 then
			restoreCam()
			if clone then clone:Destroy() clone = nil end
		end

		if not rendered then setStatus("map/egg belum render di " .. z.name) return end

		-- 4) pilih egg (terdekat / terbagus)
		local p, ppos = pickEgg(z.pos)
		if not p then setStatus("tidak ada egg di " .. z.name) return end
		result = true

		h = hrp()
		if h and (ppos - h.Position).Magnitude > 8 then
			setPos(h, ppos + Vector3.new(0, 3, 0))
			task.wait(0.1)
		end

		local info = parseEgg(p)
		setStatus(string.format("ambil %s (%s kg)", info.name, tostring(info.kg)))
		local before = carryScore()
		local got = false
		for _ = 1, 8 do
			if not (p.Parent and p.Enabled) or not cond() then break end
			fire(p)
			task.wait(0.06)
			if carryScore() > before then got = true break end
		end
		if not got then got = carryScore() > before or not (p.Parent and p.Enabled) end
		if not got then setStatus("gagal ambil egg") result = false return end

		-- 5) ke safe zone
		if method == 1 then
			setStatus(string.format("Force %d ke safe zone", settings.forcespeed))
			forceMove(CFG.SAFE, 4, settings.forcespeed, cond)
		else
			setStatus("TP ke safe zone")
			setPos(hrp(), CFG.SAFE + Vector3.new(0, 1, 0))
			task.wait(0.15)
		end
		placeEgg()
		task.wait(0.3)
		setStatus("selesai " .. z.name)
	end)
	if not ok then warn("[Senar Hub] farmZone: " .. tostring(err)) end
	finish()
	return result
end

